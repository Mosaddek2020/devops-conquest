// End-to-end ops scenario through the simulator.
import '../js/sim/index.js';
import { Session } from '../js/sim/session.js';
import { newUniverse, addServer, addLaptop, authorizeKey } from '../js/sim/machines.js';
import { stripAnsi } from '../js/git/world.js';

const uni = newUniverse();
const laptop = addLaptop(uni);
const web = addServer(uni, 'web1', { fqdn: ['shop.example.com'] });
authorizeKey(uni, laptop, 'dev', web, 'ubuntu');
const s = new Session(uni, laptop);
let fails = 0;
const run = (cmd, expect, editText) => {
  let r = s.run(cmd);
  if (r.editor && editText !== undefined) r = s.resolveEditor(r.editor, editText);
  const out = r.out.map(stripAnsi).join('\n');
  const ok = !expect || (expect instanceof RegExp ? expect.test(out) : out.includes(expect));
  if (!ok) { fails++; console.log(`✗ ${cmd}\n${out.split('\n').map(l => '    ' + l).join('\n')}`); }
  else console.log(`✓ ${cmd}`);
  return out;
};
run('ssh ubuntu@web1', /Welcome to Ubuntu/);
run('whoami && hostname', 'ubuntu\nweb1');
run('apt install -y nginx', /are you root/);
run('sudo apt install -y nginx', /Setting up nginx/);
run('systemctl is-active nginx', 'active');
run('curl -s localhost', 'Welcome to nginx');
run('sudo mkdir -p /opt/shop && sudo chown ubuntu:ubuntu /opt/shop && cd /opt/shop');
run('cat > server.js <<\'EOF\'\nconst express = require(\'express\');\nconst app = express();\nconst PORT = process.env.PORT || 3000;\nif (!process.env.DATABASE_URL) throw new Error(\'DATABASE_URL is required\');\nconst db = connect(process.env.DATABASE_URL);\napp.get(\'/health\', (req, res) => res.json({ status: \'ok\', host: os.hostname() }));\napp.get(\'/\', (req, res) => res.send(\'Shop is open\'));\napp.listen(PORT, () => console.log(`shop listening on ${PORT}`));\nEOF');
run('node server.js', /Command 'node' not found/);
run('sudo apt install -y nodejs npm', /Setting up npm/);
run('node server.js', /Cannot find module 'express'/);
run('echo \'{"name":"shop","version":"1.0.0","dependencies":{"express":"^4.21.1"}}\' > package.json && npm install', /added \d+ packages/);
run('node server.js', /DATABASE_URL is required/);
run('DATABASE_URL=postgres://db:5432/shop node server.js', /getaddrinfo ENOTFOUND db/);
run('sudo apt install -y postgresql', /Setting up postgresql/);
run('DATABASE_URL=postgres://localhost:5432/shop node server.js &', /\[1\] \d+/);
run('curl -s localhost:3000/health', '"status":"ok"');
run('kill %1; curl -s localhost:3000/health; echo code=$?', 'code=7');
run('sudo tee /etc/systemd/system/shop.service > /dev/null <<\'EOF\'\n[Unit]\nDescription=Shop API\nAfter=network.target\n\n[Service]\nUser=ubuntu\nWorkingDirectory=/opt/shop\nEnvironment=PORT=3000\nEnvironment=DATABASE_URL=postgres://localhost:5432/shop\nExecStart=/usr/bin/node server.js\nRestart=always\n\n[Install]\nWantedBy=multi-user.target\nEOF');
run('sudo systemctl daemon-reload && sudo systemctl enable --now shop', /Created symlink/);
run('systemctl status shop', /active \(running\)/);
run('journalctl -u shop -n 3', /shop listening on 3000/);
run('sudo tee /etc/nginx/sites-available/shop > /dev/null <<\'EOF\'\nserver {\n    listen 80;\n    server_name shop.example.com;\n    location / {\n        proxy_pass http://127.0.0.1:3000;\n    }\n}\nEOF');
run('sudo ln -s /etc/nginx/sites-available/shop /etc/nginx/sites-enabled/shop && sudo nginx -t', /syntax is ok/);
run('sudo systemctl reload nginx');
run('curl -s -H "Host: shop.example.com" localhost/', 'Shop is open');
run('exit', /Connection to web1 closed/);
run('curl -s http://shop.example.com/health', '"status":"ok"');
run('ssh ubuntu@web1 "sudo ufw allow OpenSSH && sudo ufw enable"', /Firewall is active/);
run('curl -s -m 3 http://shop.example.com/; echo code=$?', 'code=28');
run('ssh ubuntu@web1 "sudo ufw allow \'Nginx Full\'"', /Rule added/);
run('curl -s http://shop.example.com/', 'Shop is open');
run('ssh ubuntu@web1 "sudo systemctl stop shop"');
run('curl -s -o /dev/null -w "%{http_code}" http://shop.example.com/', '502');
run('ssh ubuntu@web1 "sudo tail -n 1 /var/log/nginx/error.log"', /Connection refused/);
run('ssh ubuntu@web1 "sudo systemctl start shop" && curl -sI http://shop.example.com/ | head -1', 'HTTP/1.1 200 OK');
run('ssh ubuntu@web1 "sudo sed -i \'s/proxy_pass http:\\/\\/127.0.0.1:3000;/proxy_pass http:\\/\\/127.0.0.1:3000/\' /etc/nginx/sites-available/shop && sudo nginx -t"', /test failed/);
run('ssh ubuntu@web1 "ps aux | grep -c node"', /\d/);
run('ssh ubuntu@web1 "sudo kill -9 $(pgrep -f server.js)"; sleep 5; ssh ubuntu@web1 "systemctl is-active shop"', 'active');
console.log(fails ? `\n${fails} failures` : '\nops scenario passes');
process.exit(fails ? 1 : 0);
