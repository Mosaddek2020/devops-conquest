// Checks the bash interpreter and core tools against expected bash output.
import { Universe, Session } from '../js/sim/index.js';
import { stripAnsi } from '../js/git/world.js';

let fails = 0, n = 0;
function fresh() { const u = new Universe(); const h = u.addHost('box', { user: 'dev' }); const s = new Session(u, h); s.advancePerCommand = 0; return { u, h, s }; }
function t(cmd, expect, { setup, code } = {}) {
  n++;
  const { s, h } = fresh();
  if (setup) setup(h, s);
  const r = s.run(cmd);
  const got = r.out.map(stripAnsi).join('\n');
  const ok = (expect instanceof RegExp ? expect.test(got) : got === expect) && (code === undefined || r.code === code);
  if (!ok) { fails++; console.log(`✗ ${cmd}\n   expected: ${JSON.stringify(expect)}${code !== undefined ? ' code ' + code : ''}\n   got:      ${JSON.stringify(got)} code ${r.code}`); }
}
const files = (map) => (h) => { for (const [p, c] of Object.entries(map)) h.writeFile(p, c, 'dev'); };

