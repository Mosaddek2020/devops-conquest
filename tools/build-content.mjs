// Bundles content/<realm>/<lesson>.md into js/content/text.js.
// Each lesson file is split on "## <kind> | <title>" headings into lenses;
// "## lab | <title>" becomes the lab brief.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'content');
const out = {};
let lensCount = 0;
for (const realm of readdirSync(contentDir).sort()) {
  const dir = join(contentDir, realm);
  if (!statSync(dir).isDirectory()) continue;
  for (const file of readdirSync(dir).filter(f => f.endsWith('.md')).sort()) {
    const lessonId = file.replace(/\.md$/, '');
    const src = readFileSync(join(dir, file), 'utf8').replace(/\r/g, '');
    const lenses = [];
    let lab = null;
    let cur = null;
    const seen = {};
    for (const line of src.split('\n')) {
      const m = line.match(/^## ([a-z]+) \| (.+)$/);
      if (m) {
        if (cur) (cur.kind === 'lab' ? (lab = cur) : lenses.push(cur));
        seen[m[1]] = (seen[m[1]] || 0) + 1;
        cur = { id: seen[m[1]] > 1 ? `${m[1]}-${seen[m[1]]}` : m[1], kind: m[1], title: m[2].trim(), md: '' };
        continue;
      }
      if (cur) cur.md += line + '\n';
    }
    if (cur) (cur.kind === 'lab' ? (lab = cur) : lenses.push(cur));
    for (const l of lenses) l.md = l.md.trim();
    if (lab) lab.md = lab.md.trim();
    lensCount += lenses.length;
    out[`${realm}/${lessonId}`] = { lenses, lab };
  }
}
writeFileSync(join(root, 'js/content/text.js'), '// Generated by tools/build-content.mjs. Edit the Markdown in content/ instead.\nexport default ' + JSON.stringify(out, null, 0) + ';\n');
console.log(`bundled ${Object.keys(out).length} lessons, ${lensCount} lenses`);
